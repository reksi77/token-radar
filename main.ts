// Token launch radar — the entrypoint.
//
// Reads the sealed snapshot, fits the value model and the token odds from
// it (see lib/model.ts), builds the ranked board, and writes the
// dashboard's output: board.json, the dashboard's data, the dashboard and
// screenshots copied in, and dossier.json from the kit's library.
//
//   MAKEFUN_OUTPUT_DIR=out node main.ts --input ../input/snapshot.json
//
// Standard library only, no network, fully deterministic: two runs write
// the same bytes. The snapshot path defaults to /input/snapshot.json (the
// grade's path) and the output directory to /output.

import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { buildBoard, DEFAULT_SCENARIO } from './lib/model.ts';
import { buildDossier } from './vendor/makefun-board.ts';

function argValue(name: string, fallback: string): string {
  const argv = process.argv.slice(2);
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === name && i + 1 < argv.length) return argv[i + 1]!;
    if (argv[i]!.startsWith(`${name}=`)) return argv[i]!.slice(name.length + 1);
  }
  return fallback;
}

function main(): void {
  const inputPath = argValue('--input', '/input/snapshot.json');
  const outDir = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';
  const root = new URL('.', import.meta.url).pathname;

  const snapshot = JSON.parse(readFileSync(inputPath, 'utf8'));
  const { rows, fit } = buildBoard(snapshot);

  // The gate's floor: at least 100 rows, and every watchlist slug covered.
  const watch = new Set<string>(snapshot.watchlist as string[]);
  const covered = rows.filter((r) => watch.has(r.slug)).length;
  if (rows.length < 100) throw new Error(`board holds ${rows.length} rows, under the 100 minimum`);
  if (covered !== watch.size) {
    throw new Error(`board covers ${covered} of ${watch.size} watchlist protocols`);
  }
  for (let i = 1; i < rows.length; i++) {
    if (rows[i]!.implied_value_usd > rows[i - 1]!.implied_value_usd) {
      throw new Error(`board is not sorted by value at rank ${i + 1}`);
    }
  }

  const totalImplied = rows.reduce((n, r) => n + r.implied_value_usd, 0);
  const verdictCounts = {
    FARM: rows.filter((r) => r.verdict === 'FARM').length,
    MARGINAL: rows.filter((r) => r.verdict === 'MARGINAL').length,
    SKIP: rows.filter((r) => r.verdict === 'SKIP').length,
  };

  const board = {
    as_of: snapshot.as_of,
    source: snapshot.source,
    floor_usd: snapshot.floor_usd,
    watchlist_total: watch.size,
    total_implied_usd: totalImplied,
    scenario_default: DEFAULT_SCENARIO,
    verdict_counts: verdictCounts,
    fit,
    rows,
  };

  const boardJson = `${JSON.stringify(board, null, 2)}\n`;
  // Seal: the sha256 of "slug:implied,slug:implied,..." over the rows in
  // rank order, so the dashboard's self-check strip can recompute it in
  // the browser from the table it draws and compare it with this value.
  const seal = createHash('sha256')
    .update(rows.map((r) => `${r.slug}:${r.implied_value_usd}`).join(','))
    .digest('hex');
  board.fit = { ...fit, seal } as typeof fit;

  mkdirSync(outDir, { recursive: true });
  mkdirSync(join(outDir, 'dashboard'), { recursive: true });
  mkdirSync(join(outDir, 'screenshots'), { recursive: true });

  // The board itself, and the dashboard's data beside the page.
  const boardJsonSealed = `${JSON.stringify(board, null, 2)}\n`;
  writeFileSync(join(outDir, 'board.json'), boardJsonSealed);
  writeFileSync(
    join(outDir, 'dashboard', 'data.js'),
    `// Generated by main.ts from the snapshot; do not edit by hand.\nwindow.BOARD = ${JSON.stringify(board, null, 2)};\n`,
  );

  // The page and its screenshots, copied in as they stand.
  cpSync(join(root, 'dashboard'), join(outDir, 'dashboard'), { recursive: true });
  const shots = join(root, 'screenshots');
  if (!existsSync(shots)) throw new Error('screenshots/ is missing: the dossier needs its cover');
  cpSync(shots, join(outDir, 'screenshots'), { recursive: true });

  // The dossier is what the scorer compares byte for byte.
  const dossier = buildDossier(outDir, { text_max_bytes: 65536 });
  writeFileSync(join(outDir, 'dossier.json'), dossier);

  console.log(`rows: ${rows.length}`);
  console.log(`watchlist covered: ${covered}/${watch.size}`);
  console.log(`fit: log(mult) = ${fit.a} + ${fit.b}*(logTVL-17) + ${fit.c}*(chg/10), population ${fit.population}`);
  console.log(`weibull: lam=${fit.weibull.lam} k=${fit.weibull.k} horizon=${fit.weibull.horizon_years}yr, median age ${fit.median_age_years}yr, age unknown ${fit.age_unknown_board_rows} rows`);
  console.log(`held-out chosen: LOO x${fit.heldout.chosen.loo.typ} (far x${fit.heldout.chosen.loo.far}) | WF x${fit.heldout.chosen.wf.typ} (far x${fit.heldout.chosen.wf.far})`);
  console.log(`held-out flat: LOO x${fit.heldout.flat.loo.typ} | WF x${fit.heldout.flat.wf.typ}; old: LOO x${fit.heldout.old.loo.typ} | WF x${fit.heldout.old.wf.typ}`);
  console.log(`coverage WF: P25-P75 ${fit.coverage.wf2575}, P10-P90 ${fit.coverage.wf1090}, within x3 ${fit.coverage.wfWithin3}`);
  console.log(`accounting: ${fit.accounting.total} = ${fit.accounting.ranked} ranked + ${fit.accounting.tokenized} tokenized + ${fit.accounting.excluded_total} excluded (${JSON.stringify(fit.accounting.excluded_by_reason)})`);
  console.log(`verdicts (default scenario): FARM ${verdictCounts.FARM}, MARGINAL ${verdictCounts.MARGINAL}, SKIP ${verdictCounts.SKIP}`);
  console.log(`implied value: ${rows[0]!.implied_value_usd} (${rows[0]!.slug}, rank 1) to ${rows[rows.length - 1]!.implied_value_usd} (rank ${rows.length}), total ${totalImplied}`);
  console.log(`seal: ${seal}`);
  console.log(`dossier: ${dossier.length} bytes`);
  console.log('ok');
}

main();
