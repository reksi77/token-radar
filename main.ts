// Token launch radar — the entrypoint.
//
// Reads the sealed snapshot, builds the ranked board, and writes the
// dashboard's output: board.json, the dashboard's data, the dashboard and
// screenshots copied in, and dossier.json from the kit's library.
//
//   MAKEFUN_OUTPUT_DIR=out node main.ts --input ../input/snapshot.json
//
// Standard library only, no network, fully deterministic: two runs write
// the same bytes. The snapshot path defaults to /input/snapshot.json (the
// grade's path) and the output directory to /output.

import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildBoard } from './lib/model.ts';
import { buildDossier } from './vendor/makefun-board.ts';

function argValue(name: string, fallback: string): string {
  const argv = process.argv.slice(2);
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === name && i + 1 < argv.length) return argv[i + 1]!;
    if (argv[i]!.startsWith(`${name}=`)) return argv[i]!.slice(name.length + 1);
  }
  return fallback;
}

function main(): void {
  const inputPath = argValue('--input', '/input/snapshot.json');
  const outDir = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';
  const root = new URL('.', import.meta.url).pathname;

  const snapshot = JSON.parse(readFileSync(inputPath, 'utf8'));
  const rows = buildBoard(snapshot);

  // The gate's floor: at least 100 rows, and every watchlist slug covered.
  const watch = new Set<string>(snapshot.watchlist as string[]);
  const covered = rows.filter((r) => watch.has(r.slug)).length;
  if (rows.length < 100) throw new Error(`board holds ${rows.length} rows, under the 100 minimum`);
  if (covered !== watch.size) {
    throw new Error(`board covers ${covered} of ${watch.size} watchlist protocols`);
  }
  for (let i = 1; i < rows.length; i++) {
    if (rows[i]!.implied_value_usd > rows[i - 1]!.implied_value_usd) {
      throw new Error(`board is not sorted by value at rank ${i + 1}`);
    }
  }

  const board = {
    as_of: snapshot.as_of,
    source: snapshot.source,
    floor_usd: snapshot.floor_usd,
    watchlist_total: watch.size,
    rows,
  };

  mkdirSync(outDir, { recursive: true });
  mkdirSync(join(outDir, 'dashboard'), { recursive: true });
  mkdirSync(join(outDir, 'screenshots'), { recursive: true });

  // The board itself, and the dashboard's data beside the page.
  writeFileSync(join(outDir, 'board.json'), `${JSON.stringify(board, null, 2)}\n`);
  writeFileSync(
    join(outDir, 'dashboard', 'data.js'),
    `// Generated by main.ts from the snapshot; do not edit by hand.\nwindow.BOARD = ${JSON.stringify(board, null, 2)};\n`,
  );

  // The page and its screenshots, copied in as they stand.
  cpSync(join(root, 'dashboard'), join(outDir, 'dashboard'), { recursive: true });
  const shots = join(root, 'screenshots');
  if (!existsSync(shots)) throw new Error('screenshots/ is missing: the dossier needs its cover');
  cpSync(shots, join(outDir, 'screenshots'), { recursive: true });

  // The dossier is what the scorer compares byte for byte.
  const dossier = buildDossier(outDir, { text_max_bytes: 65536 });
  writeFileSync(join(outDir, 'dossier.json'), dossier);

  console.log(`rows: ${rows.length}`);
  console.log(`watchlist covered: ${covered}/${watch.size}`);
  console.log(`implied value: ${rows[0]!.implied_value_usd} (rank 1) to ${rows[rows.length - 1]!.implied_value_usd} (rank ${rows.length})`);
  console.log(`dossier: ${dossier.length} bytes`);
  console.log('ok');
}

main();
